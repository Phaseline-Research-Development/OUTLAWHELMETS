"""Headless Workbench (ResourceManager module) on the PLHM_DevTools wrapper: register + rebuild files, then stop OUR PID.
python wb_plugin_run.py --reg <abs files...> --reb <abs files...> [--timeout 900]
The plugin source is generated into PLHM_DevTools/Scripts/WorkbenchGame/PLHM_ImportPlugin.c (test addon, never shipped).
"""
import os, sys, time, subprocess, glob, datetime

WB = r"C:\Users\tyler\Gaming\steamapps\common\Arma Reforger Tools\Workbench\ArmaReforgerWorkbenchSteamDiag.exe"
DEV = r"C:\Users\tyler\OneDrive\Desktop\github\OUTLAWHELMETS\_earpro\PLHM_DevTools"
ADDONS = r"C:\Users\tyler\Gaming\steamapps\common\Arma Reforger\addons,D:\PhaselineHelmetsTest\deps,C:\Users\tyler\OneDrive\Desktop\github\OUTLAWHELMETS,C:\Users\tyler\OneDrive\Desktop\github\OUTLAWHELMETS\_earpro"
LOGS = r"C:\Users\tyler\OneDrive\Documents\My Games\ArmaReforgerWorkbench\logs"
GUARD = r"C:\Users\tyler\OneDrive\Desktop\SOCOM_TRAINING_MAP\SOURCE\tools\tyler_guard.ps1"

reg, regp, reb, cur, timeout = [], [], [], None, 900
args = sys.argv[1:]
i = 0
while i < len(args):
    a = args[i]
    if a == "--reg":
        cur = reg
    elif a == "--regp":          # prefabs / worlds / configs: register WITHOUT immediate build (true hangs WB), rebuild after
        cur = regp
    elif a == "--reb":
        cur = reb
    elif a == "--timeout":
        timeout = int(args[i + 1]); i += 1
    else:
        cur.append(a.replace("\\", "/"))
    i += 1

r1 = "\n".join([f'\t\trm.RegisterResourceFile("{f}", true);' for f in reg] +
               [f'\t\trm.RegisterResourceFile("{f}", false);' for f in regp])
r2 = "\n".join(f'\t\treb.Insert("{f}");' for f in reb)
os.makedirs(os.path.join(DEV, "Scripts", "WorkbenchGame"), exist_ok=True)
open(os.path.join(DEV, "Scripts", "WorkbenchGame", "PLHM_ImportPlugin.c"), "w").write(f'''// PLHM_DevTools (test only): generated by OUTLAWHELMETS/_earpro/tools/wb_plugin_run.py
[WorkbenchPluginAttribute(name: "PLHM Import", wbModules: {{"ResourceManager"}})]
class PLHM_ImportPlugin : WorkbenchPlugin
{{
	override void RunCommandline()
	{{
		ResourceManager rm = Workbench.GetModule(ResourceManager);
		array<string> reb = {{}};
{r2}
		Print("PLHM_IMPORT_BEGIN " + reb.Count().ToString());
{r1}
		Print("PLHM_REGISTERED {len(reg) + len(regp)}");
		if (reb.Count() > 0)
			rm.RebuildResourceFiles(reb, "PC");
		Print("PLHM_IMPORT_END");
	}}
}}
''')

g = subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", f". '{GUARD}'; Test-TylerBusy"], capture_output=True, text=True)
while g.stdout.strip().lower().startswith("true"):
    print("[guard] Tyler busy - waiting", flush=True)
    time.sleep(30)
    g = subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", f". '{GUARD}'; Test-TylerBusy"], capture_output=True, text=True)

t0 = time.time()
si = subprocess.STARTUPINFO()
si.dwFlags |= subprocess.STARTF_USESHOWWINDOW
si.wShowWindow = 7
p = subprocess.Popen([WB, "-gproj", os.path.join(DEV, "addon.gproj"), "-addonsDir", ADDONS, "-wbModule=ResourceManager",
                      "-noFocus", "-noThrow", "-plugin=PLHM_ImportPlugin"], startupinfo=si)
print("headless WB pid", p.pid, flush=True)
ld = None
n = 0
end = False
while time.time() - t0 < timeout:
    time.sleep(4)
    if ld is None:
        for d in sorted(glob.glob(os.path.join(LOGS, "*")), key=os.path.getmtime, reverse=True)[:6]:
            c = os.path.join(d, "console.log")
            if os.path.getmtime(d) >= t0 - 5 and os.path.exists(c) and "PLHM_IMPORT_BEGIN" in open(c, encoding="utf-8", errors="replace").read():
                ld = d
                break
    if ld:
        txt = open(os.path.join(ld, "console.log"), encoding="utf-8", errors="replace").read()
        n = txt.count("Rebuilding took")
        end = "PLHM_IMPORT_END" in txt
        if end and n >= len(reb):
            break
        if "Can't compile" in txt:
            print("SCRIPT COMPILE FAILED - the plugin cannot run; stopping", flush=True)
            break
    if p.poll() is not None:
        break
time.sleep(5)
print(f"end={end} rebuilt {n}/{len(reb)} in {int(time.time() - t0)} s log {ld}", flush=True)
if ld:
    for ln in open(os.path.join(ld, "console.log"), encoding="utf-8", errors="replace"):
        if "(E)" in ln or "PLHM_" in ln:
            print("  ", ln.rstrip()[:300])
# stop only our process (and any child the Steam launcher handed off to, matched by our command line)
r = subprocess.run(["powershell", "-NoProfile", "-Command",
                    "Get-CimInstance Win32_Process | Where-Object { $_.Name -like 'ArmaReforgerWorkbench*' -and $_.CommandLine -like '*PLHM_ImportPlugin*' } | ForEach-Object { $_.ProcessId }"],
                   capture_output=True, text=True)
for pid in [p.pid] + [int(x) for x in r.stdout.split() if x.strip().isdigit()]:
    subprocess.run(["taskkill", "/PID", str(pid), "/F"], capture_output=True)
print("stopped own WB", flush=True)
